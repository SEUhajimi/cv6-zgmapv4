local function TI(name) local t = GameInfo.Terrains[name]; if t then return t.Index end; return nil end
local function FI(name) local f = GameInfo.Features[name]; if f then return f.Index end; return nil end

function GenerateMap()
	print("Generating Warring States China map V4.0 (2026-11-01)")
	g_iW, g_iH = Map.GetGridSize()
	local W, H = g_iW, g_iH
	pcall(function() g_iFlags = TerrainBuilder.GetFractalFlags() end)

	local TERR = {
		["~"] = TI("TERRAIN_OCEAN"),          ["c"] = TI("TERRAIN_COAST"),
		["g"] = TI("TERRAIN_GRASS"),          ["G"] = TI("TERRAIN_GRASS_HILLS"),
		["p"] = TI("TERRAIN_PLAINS"),         ["P"] = TI("TERRAIN_PLAINS_HILLS"),
		["d"] = TI("TERRAIN_DESERT"),         ["D"] = TI("TERRAIN_DESERT_HILLS"),
		["M"] = TI("TERRAIN_PLAINS_MOUNTAIN"),["S"] = TI("TERRAIN_SNOW_MOUNTAIN"),
	}

	-- 1. terrain
	for y = 0, H - 1 do
		local row = TERRAIN_ROWS[MAP_H - y]
		for x = 0, W - 1 do
			local t = TERR["~"]
			if row and x < MAP_W then t = TERR[row:sub(x + 1, x + 1)] or TERR["~"] end
			local plot = Map.GetPlot(x, y)
			if plot and t ~= nil then pcall(TerrainBuilder.SetTerrainType, plot, t) end
		end
	end
	AreaBuilder.Recalculate()
	pcall(function() TerrainBuilder.AnalyzeChokepoints() end)
	local okc, errc = pcall(function() TerrainBuilder.StampContinents() end)
	if not okc then print('StampContinents failed: ' .. tostring(errc)) end

	-- 2. gameplay rivers (for housing / defence only; the big rivers are coast tiles)
	local ok, err = pcall(function() AddRivers() end)
	if not ok then print("AddRivers failed: " .. tostring(err)) end

	-- 2b. native river edges: the Yellow River through Hangu and Luoyang (keeps the land tiles and the corridor),
	-- plus fresh water beside the coast-tile rivers (they give none). Each edge flows toward the corner nearer,
	-- along the river, to water or a game river; a river that ends on dry land is drawn with a puddle at its end.
	pcall(function()
		local f = { n = 0, ne = 1, se = 2, s = 3, sw = 4, nw = 5 }
		pcall(function()
			f.n = FlowDirectionTypes.FLOWDIRECTION_NORTH
			f.ne = FlowDirectionTypes.FLOWDIRECTION_NORTHEAST
			f.se = FlowDirectionTypes.FLOWDIRECTION_SOUTHEAST
			f.s = FlowDirectionTypes.FLOWDIRECTION_SOUTH
			f.sw = FlowDirectionTypes.FLOWDIRECTION_SOUTHWEST
			f.nw = FlowDirectionTypes.FLOWDIRECTION_NORTHWEST
		end)
		-- corners on an integer lattice: plot centre (2x + odd row, 3y), corners at (0,+-2) and (+-1,+-1)
		local function V(x, y, dx, dy) return (3 * y + dy + 10) * 1000 + (2 * x + (y % 2) + dx + 10) end
		local TOP, C30, C330, BOT, C210, C150 = { 0, 2 }, { 1, 1 }, { 1, -1 }, { 0, -2 }, { -1, -1 }, { -1, 1 }
		-- per direction from p to q: the shared corners (in p's frame), which plot carries the edge, and the flow toward each corner
		local SIDE = {
			[0] = { TOP, C30, "NE", true, f.nw, f.se },
			[1] = { C30, C330, "W", false, f.n, f.s },
			[2] = { C330, BOT, "NW", false, f.ne, f.sw },
			[3] = { BOT, C210, "NE", false, f.se, f.nw },
			[4] = { C210, C150, "W", true, f.s, f.n },
			[5] = { C150, TOP, "NW", true, f.sw, f.ne },
		}
		local list = {}
		for _, r in ipairs(RIVER_PAIRS) do list[#list + 1] = r end
		for _, c in ipairs(YELLOW_EDGE_CELLS) do
			for _, dir in ipairs({ 2, 3 }) do
				local q = Map.GetAdjacentPlot(c.x, c.y, dir)
				if q ~= nil then list[#list + 1] = { c.x, c.y, q:GetX(), q:GetY() } end
			end
		end
		local edges, at = {}, {}
		for _, r in ipairs(list) do
			local p, q = Map.GetPlot(r[1], r[2]), Map.GetPlot(r[3], r[4])
			if p ~= nil and q ~= nil then
				for dir = 0, 5 do
					local adj = Map.GetAdjacentPlot(r[1], r[2], dir)
					if adj ~= nil and adj:GetX() == r[3] and adj:GetY() == r[4] then
						local s = SIDE[dir]
						local e = { plot = s[4] and q or p, kind = s[3], flowA = s[5], flowB = s[6],
							a = V(r[1], r[2], s[1][1], s[1][2]), b = V(r[1], r[2], s[2][1], s[2][2]) }
						edges[#edges + 1] = e
						at[e.a] = at[e.a] or {}; table.insert(at[e.a], e)
						at[e.b] = at[e.b] or {}; table.insert(at[e.b], e)
						break
					end
				end
			end
		end
		-- sinks: corners touching water and corners on the game's own rivers
		local dist, queue = {}, {}
		local function Sink(k) if at[k] ~= nil and dist[k] == nil then dist[k] = 0; queue[#queue + 1] = k end end
		for i = 0, W * H - 1 do
			local p = Map.GetPlotByIndex(i)
			if p ~= nil then
				local x, y = p:GetX(), p:GetY()
				if p:IsWater() then
					for _, c in ipairs({ TOP, C30, C330, BOT, C210, C150 }) do Sink(V(x, y, c[1], c[2])) end
				else
					if p:IsWOfRiver() then Sink(V(x, y, 1, 1)); Sink(V(x, y, 1, -1)) end
					if p:IsNWOfRiver() then Sink(V(x, y, 1, -1)); Sink(V(x, y, 0, -2)) end
					if p:IsNEOfRiver() then Sink(V(x, y, 0, -2)); Sink(V(x, y, -1, -1)) end
				end
			end
		end
		local head = 1
		while head <= #queue do
			local k = queue[head]; head = head + 1
			for _, e in ipairs(at[k]) do
				local o = (e.a == k) and e.b or e.a
				if dist[o] == nil then dist[o] = dist[k] + 1; queue[#queue + 1] = o end
			end
		end
		-- one river id per connected group of edges, after the ids the game's rivers used
		local id, nextId = {}, (nextRiverID or 0) + 1
		for _, e in ipairs(edges) do
			if id[e] == nil then
				local stack = { e }; id[e] = nextId
				while #stack > 0 do
					local g = table.remove(stack)
					for _, k in ipairs({ g.a, g.b }) do
						for _, h in ipairs(at[k]) do
							if id[h] == nil then id[h] = nextId; table.insert(stack, h) end
						end
					end
				end
				nextId = nextId + 1
			end
		end
		nextRiverID = nextId
		local made, dry = 0, 0
		for _, e in ipairs(edges) do
			local da, db = dist[e.a], dist[e.b]
			if da == nil then dry = dry + 1 end
			local flow = (da ~= nil and (db == nil or da <= db)) and e.flowA or e.flowB
			local p = e.plot
			if e.kind == "NE" and not p:IsNEOfRiver() then TerrainBuilder.SetNEOfRiver(p, true, flow, id[e]); made = made + 1
			elseif e.kind == "W" and not p:IsWOfRiver() then TerrainBuilder.SetWOfRiver(p, true, flow, id[e]); made = made + 1
			elseif e.kind == "NW" and not p:IsNWOfRiver() then TerrainBuilder.SetNWOfRiver(p, true, flow, id[e]); made = made + 1 end
		end
		print("Native river edges placed: " .. tostring(made) .. " (" .. tostring(dry) .. " not reaching water)")
	end)

	-- 3. features
	local FEAT = { f = FI("FEATURE_FOREST"), j = FI("FEATURE_JUNGLE"), m = FI("FEATURE_MARSH") }
	for y = 0, H - 1 do
		local row = FEATURE_ROWS[MAP_H - y]
		if row then
			for x = 0, W - 1 do
				local ch = row:sub(x + 1, x + 1)
				local idx = FEAT[ch]
				if idx ~= nil then
					local plot = Map.GetPlot(x, y)
					local good, _ = pcall(function()
						if TerrainBuilder.CanHaveFeature(plot, idx) then
							TerrainBuilder.SetFeatureType(plot, idx)
						end
					end)
				end
			end
		end
	end
	AreaBuilder.Recalculate()
	pcall(function() TerrainBuilder.StampContinents() end)

	-- 3a. cliffs along the Nanjing stretch of the Yangtze: land units cannot embark/disembark except from cities
	pcall(function()
		for _, c in ipairs(CLIFF_CELLS) do
			local plot = Map.GetPlot(c.x, c.y)
			if plot ~= nil then
				for dir = 0, 5 do
					local adj = Map.GetAdjacentPlot(c.x, c.y, dir)
					if adj ~= nil and adj:IsWater() then
						if dir == 0 then TerrainBuilder.SetNEOfCliff(adj, true)
						elseif dir == 1 then TerrainBuilder.SetWOfCliff(plot, true)
						elseif dir == 2 then TerrainBuilder.SetNWOfCliff(plot, true)
						elseif dir == 3 then TerrainBuilder.SetNEOfCliff(plot, true)
						elseif dir == 4 then TerrainBuilder.SetWOfCliff(adj, true)
