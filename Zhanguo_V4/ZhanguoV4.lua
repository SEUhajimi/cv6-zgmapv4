		local keep = {}
		for _, c in ipairs(KEEP_CELLS) do keep[c.y * W + c.x] = true end
		-- city-states too (the engine's AddGoodies keeps villages off every start, ours must as well)
		local minorStarts = {}
		for _, pid in ipairs(PlayerManager.GetAliveMinorIDs()) do
			local sp = Players[pid]:GetStartingPlot()
			if sp then minorStarts[#minorStarts + 1] = sp end
		end
		local cand = {}
		local landCount = 0
		for k = 0, W * H - 1 do
			local p = Map.GetPlotByIndex(k)
			if p ~= nil and not p:IsWater() and not p:IsMountain() then
				landCount = landCount + 1
				local ok = (p:GetImprovementType() < 0) and (p:GetResourceType() < 0) and (not p:IsNaturalWonder()) and (not keep[k])
				if ok then
					for _, sp in ipairs(START_POSITIONS) do
						if Map.GetPlotDistance(p:GetX(), p:GetY(), sp.x, sp.y) < 7 then ok = false; break end
					end
				end
				if ok then
					for _, sp in ipairs(minorStarts) do
						if Map.GetPlotDistance(p:GetX(), p:GetY(), sp:GetX(), sp:GetY()) < 4 then ok = false; break end
					end
				end
				if ok then cand[#cand + 1] = k end
			end
		end
		local target = math.floor(landCount / 35)
		if have >= target then print("Goodies: enough villages already"); return end
		for i = #cand, 2, -1 do
			local j = TerrainBuilder.GetRandomNumber(i, "Hut shuffle") + 1
			cand[i], cand[j] = cand[j], cand[i]
		end
		local made = 0
		for _, k in ipairs(cand) do
			if have + made >= target then break end
			local p = Map.GetPlotByIndex(k)
			local far = true
			for _, q in ipairs(placed) do
				if Map.GetPlotDistance(p:GetX(), p:GetY(), q.x, q.y) < 3 then far = false; break end
			end
			if far then
				local okp = pcall(function() ImprovementBuilder.SetImprovementType(p, hutIdx, -1) end)
				if okp then placed[#placed + 1] = { x = p:GetX(), y = p:GetY() }; made = made + 1 end
			end
		end
		print("Goodies: added " .. tostring(made) .. " tribal villages (target " .. tostring(target) .. ")")
	end)
	-- 7. resource summary, to judge the resource settings from Lua.log
	pcall(function()
		local count = { RESOURCECLASS_LUXURY = 0, RESOURCECLASS_STRATEGIC = 0, RESOURCECLASS_BONUS = 0 }
		for k = 0, W * H - 1 do
			local info = ResInfo(Map.GetPlotByIndex(k))
			if info and count[info.ResourceClassType] ~= nil then
				count[info.ResourceClassType] = count[info.ResourceClassType] + 1
			end
		end
		print("Resources: luxury " .. count.RESOURCECLASS_LUXURY .. ", strategic " .. count.RESOURCECLASS_STRATEGIC
			.. ", bonus " .. count.RESOURCECLASS_BONUS)
		for _, pid in ipairs(PlayerManager.GetAliveMajorIDs()) do
			local sp = Players[pid]:GetStartingPlot()
			if sp then
				local usable, bonus, lux, strategic = StartInfo(sp)
				print("Resources: player " .. tostring(pid) .. " at (" .. sp:GetX() .. "," .. sp:GetY() .. ") within 3: usable land "
					.. usable .. ", bonus " .. #bonus .. "; within 6: luxury types " .. lux .. ", strategic " .. strategic)
			end
		end
	end)
	print("Warring States map done")
end
